def _split_report(source: str) -> tuple[str, str]:
    """Split a helper source into (definitions, report lines run in the notebook)."""
    text = source.strip("\n")
    match = REPORT_START.search(text)
    if match is None:
        return text, ""
    return text[: match.start()].rstrip("\n"), text[match.start() :].strip("\n")


# Module state that the helpers rebind (global ...). A star import would copy the value once and
# go stale, so these names stay out of __all__; use stop_shared_redis(), shared_redis_id(), ...
MODULE_STATE = {"redis_container", "pg_container"}


def _public_names(module_text: str) -> list[str]:
    """Top-level names the module defines (not the modules it imports), without leading _."""
    names: list[str] = []
    for node in ast.parse(module_text).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.append(node.name)
        elif isinstance(node, ast.Assign):
            names += [target.id for target in node.targets if isinstance(target, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.append(node.target.id)
    return sorted(dict.fromkeys(name for name in names if not name.startswith("_")))


def module_source() -> str:
    """The text of notebooks/phase6_helpers.py."""
    parts = [MODULE_HEADER.strip("\n")]
    for title, unit, source in helper_groups():
        definitions, _ = _split_report(source)
        banner = f"# --- {title} (Unit {unit}) "
        parts.append(banner + "-" * (100 - len(banner)) + "\n\n\n" + definitions)
    body = "\n\n\n".join(parts)
    names = [name for name in _public_names(body) if name not in MODULE_STATE]
    exports = "".join(f'    "{name}",\n' for name in names)
    return f"{body}\n\n\n__all__ = [\n{exports}]\n"


def write_module(notebooks_dir: Path) -> Path:
    """Write the helper module next to the notebook and return its path."""
    path = notebooks_dir / f"{MODULE_NAME}.py"
    path.write_text(module_source(), encoding="utf-8")
    return path


def _report_source(unit: str) -> str:
    """The version / flag lines of the helper groups the unit introduces.

    Always starts with the interpreter; from Unit 6.4 on it also says whether Docker is there.
    The project prints Unit 6.8's report.
    """
    unit = "6.8" if unit == "project" else unit
    groups = {group_unit: "" for _, group_unit, _ in helper_groups()}
    for _, group_unit, source in helper_groups():
        groups[group_unit] += _split_report(source)[1] + "\n"
    lines = ["print(interpreter_label())"]
    if UNIT_ORDER.index(unit) >= UNIT_ORDER.index("6.4") and "HAS_DOCKER" not in groups[unit]:
        lines += [line for line in groups["6.4"].splitlines() if "HAS_DOCKER" in line]
    lines += groups.get(unit, "").splitlines()
    return "\n".join(dict.fromkeys(line for line in lines if line))


def _statements(source: str) -> list[list[str]]:
    """Split source into top-level statements; comment lines stay with the statement below.

    Blank lines stay at the end of the statement before them (they separate import groups).
    """
    lines = source.strip("\n").splitlines()
    starts = [node.lineno - 1 for node in ast.parse("\n".join(lines)).body]
    for index, start in enumerate(starts):
        while start > 0 and lines[start - 1].lstrip().startswith("#"):
            start -= 1
        starts[index] = start
    starts[0] = 0
    ends = starts[1:] + [len(lines)]
    return [lines[start:end] for start, end in zip(starts, ends, strict=True)]


def _chunks(source: str, max_lines: int = MAX_CELL_LINES) -> list[str]:
    """Group whole statements into chunks of at most max_lines lines (imports stay sorted)."""
    chunks: list[list[str]] = [[]]
    for statement in _statements(source):
        size = len("\n".join(chunks[-1]).strip("\n").splitlines())
        if chunks[-1] and size + len("\n".join(statement).strip("\n").splitlines()) > max_lines:
            chunks.append([])
        chunks[-1].extend(statement)
    return ["\n".join(chunk).strip("\n") for chunk in chunks if chunk]


def setup_cells(
    unit: str,
    imports_source: str,
    intro_markdown: str,
    *,
    folders: str = "",
    extra_source: str = "",
    report_source: str | None = None,
) -> list[NotebookNode]:
    """Part 1 (the unit's imports) and Part 2 (the shared helpers) of a unit's setup.

    Args:
        unit: "6.1" ... "6.8" or "project" (decides which group reports are printed).
        imports_source: the unit's import statements (split into cells of at most 40 lines).
        intro_markdown: the markdown for Part 2 (which helpers the unit relies on).
        folders: the arguments of enter_phase6(...), e.g. "*NOTES_FOLDERS".
        extra_source: unit-specific statements run after the helpers are imported.
        report_source: replaces the default report (each helper group's version lines).
    """
    import_chunks = _chunks(imports_source)
    cells: list[NotebookNode] = [code(import_chunks[0])]
    for chunk in import_chunks[1:]:
        cells += [md("Part 1, continued:"), code(chunk)]
    report = _report_source(unit) if report_source is None else report_source.strip("\n")
    folder_lines = [line.strip() for line in folders.strip().splitlines() if line.strip()]
    if len(folder_lines) > 1:
        call = "enter_phase6(\n" + "".join(f"    {line}\n" for line in folder_lines) + ")"
    else:
        call = f"enter_phase6({''.join(folder_lines)})"
    body = [f"from {MODULE_NAME} import *  # exactly the names in its __all__", call]
    if extra_source.strip():
        body.append(extra_source.strip("\n"))
    body.append(report)
    cells += [md(intro_markdown), code(_join_blocks(body))]
    return cells


def _join_blocks(blocks: list[str]) -> str:
    """Join code blocks with one blank line, or two next to a def/class (as ruff formats)."""
    definitions = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
    text = blocks[0]
    for previous, block in zip(blocks, blocks[1:], strict=False):
        ends_with_def = isinstance(ast.parse(previous).body[-1], definitions)
        starts_with_def = isinstance(ast.parse(block).body[0], definitions)
        text += ("\n\n\n" if ends_with_def or starts_with_def else "\n\n") + block
    return text


def helper_table_markdown(indent: int = 12) -> str:
    """A table of the module's groups and their names, for Unit 6.1's setup explanation.

    Every line but the first is indented by indent spaces, so the table can sit inside the
    indented triple-quoted markdown that md() dedents.
    """
    rows = []
    for title, unit, source in helper_groups():
        definitions, _ = _split_report(source)
        public = [name for name in _public_names(definitions) if name not in MODULE_STATE]
        names = ", ".join(f"`{name}`" for name in public)
        rows.append(f"| {title} | {unit} | {names} |")
    lines = ["| Group | Unit | Names |", "| --- | --- | --- |", *rows]
    return ("\n" + " " * indent).join(lines)
